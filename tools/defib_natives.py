#!/usr/bin/env python3
"""Papyrus native-function tools for Defib remakes and re-ports. Reads Vitals.jsonl (bPapyrusNatives=1).

  defib_natives.py summary Vitals.jsonl
      How many natives each DLL registered.
  defib_natives.py stubs Vitals.jsonl --module SomeMod.dll [--out stubs_dir]
      Papyrus-style declarations for every native that DLL registered, grouped by script. This is the
      interface a clean-room remake has to match (names and signatures only; no code is copied).
  defib_natives.py diff OLD.jsonl NEW.jsonl [--module SomeMod.dll]
      What changed between two sessions (e.g. the old build's report vs. a port's): missing, added,
      or changed-signature natives. Empty output = same interface.

Read-only. Standard library only.
"""
import argparse
import json
import os
import sys
from collections import Counter, defaultdict


def load(path):
    out = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for ln in f:
            try:
                r = json.loads(ln)
            except json.JSONDecodeError:
                continue
            if r.get("kind") == "papyrus_native":
                out.append(r)
    return out


def sig(r):
    names = r.get("params") or []
    types = r.get("param_types") or ["?"] * len(names)
    args = ", ".join(f"{t} {n}" for t, n in zip(types, names))
    ret = r.get("returns", "?")
    ret = "" if ret == "None" else ret + " "
    return f"{ret}Function {r['function']}({args}) native" + (" global" if r.get("static") else "")


def key(r):
    return (r["module"], r["script"], r["function"])


def cmd_summary(a):
    c = Counter(r["module"] for r in load(a.file))
    for m, n in c.most_common():
        print(f"{m}: {n}")


def cmd_stubs(a):
    recs = [r for r in load(a.file) if r["module"].lower() == a.module.lower()]
    if not recs:
        sys.exit(f"no natives from {a.module} in {a.file}")
    by_script = defaultdict(list)
    for r in recs:
        by_script[r["script"]].append(r)
    for script, fns in sorted(by_script.items()):
        text = f"; Interface of {a.module} (generated by Vitals; signatures only)\nScriptName {script}\n\n"
        text += "\n".join(sig(r) for r in sorted(fns, key=lambda r: r["function"].lower())) + "\n"
        if a.out:
            os.makedirs(a.out, exist_ok=True)
            with open(os.path.join(a.out, f"{script}.psc.txt"), "w", encoding="utf-8") as f:
                f.write(text)
        else:
            print(text)
    if a.out:
        print(f"wrote {len(by_script)} stub file(s) to {a.out}")


def cmd_diff(a):
    def index(path):
        d = {}
        for r in load(path):
            if a.module and r["module"].lower() != a.module.lower():
                continue
            d[(r["script"], r["function"])] = sig(r)
        return d

    old, new = index(a.old), index(a.new)
    for k in sorted(old.keys() - new.keys()):
        print(f"MISSING  {k[0]}.{k[1]}: {old[k]}")
    for k in sorted(new.keys() - old.keys()):
        print(f"ADDED    {k[0]}.{k[1]}: {new[k]}")
    for k in sorted(old.keys() & new.keys()):
        if old[k] != new[k]:
            print(f"CHANGED  {k[0]}.{k[1]}: {old[k]}  ->  {new[k]}")
    print(f"# {len(old)} old, {len(new)} new", file=sys.stderr)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("summary"); s.add_argument("file"); s.set_defaults(fn=cmd_summary)
    s = sub.add_parser("stubs"); s.add_argument("file"); s.add_argument("--module", required=True); s.add_argument("--out"); s.set_defaults(fn=cmd_stubs)
    s = sub.add_parser("diff"); s.add_argument("old"); s.add_argument("new"); s.add_argument("--module"); s.set_defaults(fn=cmd_diff)
    a = ap.parse_args(argv)
    a.fn(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
